package gitattr_test

import (
	"testing"

	"github.com/kyleking/slop-strata/internal/gitattr"
)

func TestGeneratedFollowsTheLastMatchingRule(t *testing.T) {
	t.Parallel()
	src := []byte("# generated by the build\n" +
		"*.pb.go linguist-generated\n" +
		"/api/*.go linguist-generated=true\n" +
		"legacy.pb.go -linguist-generated\n" +
		"**/vendored.go linguist-generated\n" +
		"other.go text\n")
	m, err := gitattr.Parse(src)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	cases := []struct {
		path string
		want bool
	}{
		{path: "svc/user.pb.go", want: true},
		{path: "legacy.pb.go", want: false},
		{path: "api/routes.go", want: true},
		{path: "lib/api/routes.go", want: false},
		{path: "deep/vendored.go", want: true},
		{path: "other.go", want: false},
		{path: "main.go", want: false},
	}
	for _, tc := range cases {
		if got := m.Generated(tc.path); got != tc.want {
			t.Errorf("Generated(%q) = %v, want %v", tc.path, got, tc.want)
		}
	}
}
