const sleepSrc = "package p\n\nimport \"time\"\n\nfunc wait() { time.Sleep(1) }\n"

func TestSameBlobUnderOtherPathClassKeepsItsFindings(t *testing.T) {
	t.Parallel()
	ctx := t.Context()
	store, err := cache.Open(ctx, filepath.Join(t.TempDir(), "blobs.db"))
	if err != nil {
		t.Fatalf("opening cache: %v", err)
	}
	t.Cleanup(func() {
		if err := store.Close(); err != nil {
			t.Errorf("closing cache: %v", err)
		}
	})
	eng := engine.New(config.Default(), store)
	const sha = "0123456789abcdef"

	test := eng.Analyze(ctx, "pkg/wait_test.go", sha, []byte(sleepSrc))
	source := eng.Analyze(ctx, "pkg/wait.go", sha, []byte(sleepSrc))

	if got := countRule(test.Findings, "go/timing-hack"); got != 1 {
		t.Errorf("test path go/timing-hack = %d, want 1", got)
	}
	if got := countRule(source.Findings, "go/timing-hack"); got != 0 {
		t.Errorf("source path go/timing-hack = %d, want 0", got)
	}
}

func TestPrefetchMatchesSerialAnalysis(t *testing.T) {
	t.Parallel()
	ctx := t.Context()
	store, err := cache.Open(ctx, "")
	if err != nil {
		t.Fatalf("opening cache: %v", err)
	}
	reqs := make([]engine.Request, 0, 40)
	for i := range 40 {
		src := fmt.Sprintf("package p\n\nimport \"time\"\n\nfunc f%d(a int) int {\n\tif a > %d {\n"+
			"\t\ttime.Sleep(1)\n\t\treturn a\n\t}\n\treturn 0\n}\n", i, i)
		reqs = append(reqs, engine.Request{
			Path: fmt.Sprintf("pkg/f%d_test.go", i), SHA: fmt.Sprintf("%040d", i), Content: []byte(src),
		})
	}

	parallel := engine.New(config.Default(), store)
	parallel.Prefetch(ctx, reqs)
	serial := engine.New(config.Default(), store)
	for _, r := range reqs {
		got := parallel.Analyze(ctx, r.Path, r.SHA, r.Content)
		want := serial.Analyze(ctx, r.Path, r.SHA, r.Content)
		if !reflect.DeepEqual(got.Findings, want.Findings) || !reflect.DeepEqual(got.Metrics, want.Metrics) {
			t.Fatalf("%s: prefetched report differs from serial analysis", r.Path)
		}
	}
}

func countRule(fs []rules.Finding, rule string) int {
	n := 0
	for _, f := range fs {
		if f.Rule == rule {
			n++
		}
	}

	return n
}

func TestGeneratedFilesAreSkipped(t *testing.T) {
	t.Parallel()
	ctx := t.Context()
	marked := "package p\n\n// Code generated by protoc. DO NOT EDIT.\n\nfunc f() {}\n"
	late := "package p\n\n\n\n\n\n// Code generated by protoc. DO NOT EDIT.\n\nfunc f() {}\n"
	cases := []struct {
		name    string
		path    string
		src     string
		skipped string
		opts    []engine.Option
	}{
		{name: "generator marker in the header", path: "a.go", src: marked, skipped: engine.ReasonGenerated},
		{name: "marker below the header stays scored", path: "a.go", src: late},
		{
			name: "gitattributes mark", path: "gen/a.go", src: "package p\n\nfunc f() {}\n",
			opts:    []engine.Option{engine.WithGenerated(func(p string) bool { return p == "gen/a.go" })},
			skipped: engine.ReasonGenerated,
		},
	}
	store, err := cache.Open(ctx, "")
	if err != nil {
		t.Fatalf("opening cache: %v", err)
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			eng := engine.New(config.Default(), store, tc.opts...)
			rep := eng.Analyze(ctx, tc.path, "0123456789abcdef", []byte(tc.src))
			if rep.Skipped != tc.skipped {
				t.Errorf("Skipped = %q, want %q", rep.Skipped, tc.skipped)
			}
		})
	}
}
